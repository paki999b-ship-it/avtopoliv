/**
 * Цвета кривых насосов на графике подбора (§5.11).
 *
 * Восемь различимых цветов, читаемых и на светлом, и на тёмном фоне. Цвет
 * назначается **по порядку в отсортированном списке подходящих насосов**, а не
 * случайно: при повторном расчёте с теми же исходными данными первый насос
 * снова будет синим. Иначе цвета «прыгали» бы между запусками, и сравнить два
 * расчёта глазами стало бы невозможно.
 *
 * Если подходящих насосов больше восьми, на графике показываются первые
 * восемь по сортировке — остальные остаются списком карточек. Девятый цвет не
 * генерируется: он неизбежно оказался бы неотличим от одного из восьми.
 */
export const PUMP_CURVE_COLORS = [
  '#2563EB', // синий
  '#DC2626', // красный
  '#059669', // зелёный
  '#D97706', // оранжевый
  '#7C3AED', // фиолетовый
  '#DB2777', // розовый
  '#0891B2', // бирюзовый
  '#65A30D', // оливковый
] as const;

/** Сколько кривых насосов помещается на график, не превращая его в кашу. */
export const MAX_PUMP_CURVES_ON_CHART = PUMP_CURVE_COLORS.length;

/** Цвет кривой по её месту в списке подобранных насосов. */
export function pumpCurveColor(index: number): string {
  return PUMP_CURVE_COLORS[index % PUMP_CURVE_COLORS.length]!;
}

/** Характеристика системы рисуется нейтральным цветом и пунктиром. */
export const SYSTEM_CURVE_COLOR = 'rgb(var(--iw-text-dim))';
