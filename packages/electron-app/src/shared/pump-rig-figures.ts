/**
 * Состав схем обвязки насосного узла (уровень 7 Академии).
 *
 * Данные вынесены из компонента отдельно, потому что их читает не только
 * отрисовка: тест наполнения Академии сверяет, что у каждой схемы из урока
 * есть чертёж. Список, переписанный в тесте руками, разошёлся бы с этим при
 * первом же добавлении урока.
 */

export interface RigPart {
  /** Подпись на элементе — коротко, одно-два слова. */
  label: string;
  /** Пояснение под элементом. */
  note?: string;
  /** Элемент, ради которого нарисована схема, — выделяется акцентом. */
  highlight?: boolean;
}

export interface RigConfig {
  /** Элементы всасывающей линии, от источника к насосу. */
  suction: RigPart[];
  /** Элементы напорной линии, от насоса к системе. */
  discharge: RigPart[];
  /** Электрическая часть и автоматика — рисуется сверху пунктиром. */
  control?: RigPart[];
  /** Что подписано под схемой. */
  note?: string;
  /** Подпись левого края: обычно источник. */
  sourceLabel?: string;
  /** Текст для читалки с экрана. */
  alt: string;
}

