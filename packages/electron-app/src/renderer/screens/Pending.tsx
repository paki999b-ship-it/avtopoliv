export function Pending({ sectionName }: { sectionName: string }) {
  const navigate = useRouter((s) => s.navigate);
  const item = NAV_ITEMS.find((n) => n.name === sectionName);
  const plan = PLANS[sectionName];

  return (
    <div className="mx-auto max-w-3xl px-8 py-10">
      <div className="flex items-center gap-3 mb-2">
        <span className="text-3xl" aria-hidden>
          {item?.icon ?? '📦'}
        </span>
        <h1 className="text-[24px] font-semibold tracking-tight">
          {item?.title ?? 'Раздел'}
        </h1>
        <Badge tone="warn">в разработке</Badge>
      </div>
      <p className="text-muted mb-7">{item?.hint}</p>

      <Card
        title="Что здесь будет"
        subtitle={plan ? `Собирается на этапе «${plan.step}» плана работ` : undefined}
      >
        {plan ? (
          <ul className="text-[14px] text-muted space-y-2 list-disc pl-5">
            {plan.items.map((line) => (
              <li key={line}>{line}</li>
            ))}
          </ul>
        ) : (
          <p className="text-[14px] text-muted">Раздел готовится.</p>
        )}
      </Card>

      <div className="mt-6">
        <Button variant="ghost" onClick={() => navigate({ name: 'home' })}>
          ← К обзору
        </Button>
      </div>
    </div>
  );
}
